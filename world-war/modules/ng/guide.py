def guide_menu_rows() -> list[list[tuple[str, str]]]:
    rows = []
    pair = []
    for key, label in GUIDE_MENU_ORDER:
        pair.append((label, f"ng:guide:{key}:0"))
        if len(pair) == 2:
            rows.append(pair)
            pair = []
    if pair:
        rows.append(pair)
    rows.append([("🏠 منوی اصلی", "ng:home")])
    return rows


def guide_page(section: str, page: int) -> tuple[str, list[list[tuple[str, str]]]]:
    sec = GUIDE_SECTIONS.get(section)
    if not sec:
        return "بخش راهنما یافت نشد.", [[("📖 منوی راهنما", "ng:guide"), ("🏠 منوی اصلی", "ng:home")]]
    pages = sec["pages"]
    page = max(0, min(int(page), len(pages) - 1))
    text = pages[page]
    if len(pages) > 1:
        text += f"\n\n📄 صفحه {page + 1} از {len(pages)}"
    nav = []
    if page > 0:
        nav.append(("⬅️ قبلی", f"ng:guide:{section}:{page - 1}"))
    if page + 1 < len(pages):
        nav.append(("بعدی ➡️", f"ng:guide:{section}:{page + 1}"))
    rows = []
    if nav:
        rows.append(nav)
    rows.append([("📖 منوی راهنما", "ng:guide"), ("🏠 منوی اصلی", "ng:home")])
    return text, rows
